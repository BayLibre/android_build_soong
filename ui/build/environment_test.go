func TestEnvUnset(t *testing.T) {
	initial := &Environment{"TEST=1", "TEST2=0"}
	initial.Unset("TEST")
	got := initial.Environ()
	if len(got) != 1 || got[0] != "TEST2=0" {
		t.Errorf("Expected [TEST2=0], got: %v", got)
	}
}

