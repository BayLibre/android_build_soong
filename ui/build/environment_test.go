func TestEnvAppendFromKati(t *testing.T) {
	contents := []byte(`#!/bin/sh
# Generated by kati unknown

unset 'CLANG'
export 'BUILD_ID'='NYC'
`)
	tmpfile, err := ioutil.TempFile("", "env")
	if err != nil {
		t.Fatalf("Unexpected error from TempFile: %v", err)
	}
	defer os.Remove(tmpfile.Name())

	if _, err := tmpfile.Write(contents); err != nil {
		t.Fatalf("Unexpected error from Write: %v", err)
	}
	if err := tmpfile.Close(); err != nil {
		t.Fatalf("Unexpected error from Close: %v", err)
	}

	initial := &Environment{"CLANG=/usr/bin/clang", "TEST=0"}
	err = initial.AppendFromKati(tmpfile.Name())
	if err != nil {
		t.Fatalf("Unexpected error from %v", err)
	}

	got := initial.Environ()
	expected := []string{"TEST=0", "BUILD_ID=NYC"}
	if !reflect.DeepEqual(got, expected) {
		t.Errorf("Environment list does not match")
		t.Errorf("expected: %v", expected)
		t.Errorf("     got: %v", got)
	}
}
