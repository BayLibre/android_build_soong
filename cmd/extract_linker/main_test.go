package main

import (
	"bytes"
	"testing"
)

var bytesToAsmTestCases = []struct {
	name string
	in   []byte
	out  string
}{
	{
		name: "empty",
		in:   []byte{},
		out:  "",
	},
	{
		name: "short",
		in:   []byte{0x7f, 0x45, 0x4c, 0x46, 0x02, 0x01},
		out:  ".byte 0x7f,0x45,0x4c,0x46,0x2,0x1\n",
	},
	{
		name: "quad",
		in:   []byte{0x7f, 0x45, 0x4c, 0x46, 0x02, 0x01, 0x01, 0x00},
		out:  ".quad 0x10102464c457f\n",
	},
	{
		name: "quad and short",
		in:   []byte{0x7f, 0x45, 0x4c, 0x46, 0x02, 0x01, 0x01, 0x00, 0x00},
		out:  ".quad 0x10102464c457f\n.byte 0x0\n",
	},
	{
		name: "quad multiline",
		in: []byte{0x7f, 0x45, 0x4c, 0x46, 0x02, 0x01, 0x01, 0x00,
			0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
			0x30, 0x00, 0x3e, 0x00, 0x01, 0x00, 0x00, 0x00,
			0x50, 0x98, 0x02, 0x00, 0x00, 0x00, 0x00, 0x00,
			0x40, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
			0x88, 0xd1, 0x12, 0x00, 0x00, 0x00, 0x00, 0x00,
			0x00, 0x00, 0x00, 0x00, 0x40, 0x00, 0x38, 0x00},
		out: ".quad 0x10102464c457f,0x0,0x1003e0030,0x29850,0x40,0x12d188\n" +
			".quad 0x38004000000000\n",
	},
	{
		name: "quad multiline and bytes",
		in: []byte{0x7f, 0x45, 0x4c, 0x46, 0x02, 0x01, 0x01, 0x00,
			0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
			0x30, 0x00, 0x3e, 0x00, 0x01, 0x00, 0x00, 0x00,
			0x50, 0x98, 0x02, 0x00, 0x00, 0x00, 0x00, 0x00,
			0x40, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00,
			0x88, 0xd1, 0x12, 0x00, 0x00, 0x00, 0x00, 0x00,
			0x00, 0x00, 0x00, 0x00, 0x40, 0x00, 0x38, 0x00,
			0x10, 0x00, 0x00, 0x00, 0x00, 0x00, 0x20},
		out: ".quad 0x10102464c457f,0x0,0x1003e0030,0x29850,0x40,0x12d188\n" +
			".quad 0x38004000000000\n" +
			".byte 0x10,0x0,0x0,0x0,0x0,0x0,0x20\n",
	},
}

func TestBytesToAsm(t *testing.T) {
	for _, testcase := range bytesToAsmTestCases {
		t.Run(testcase.name, func(t *testing.T) {
			buf := bytes.Buffer{}
			bytesToAsm(&buf, testcase.in)
			if buf.String() != testcase.out {
				t.Errorf("input: %x\n want: %q\n  got: %q\n", testcase.in, testcase.out, buf.String())
			}
		})
	}
}
